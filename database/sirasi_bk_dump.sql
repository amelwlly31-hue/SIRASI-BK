CREATE DATABASE IF NOT EXISTS `sirasi_bk` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `sirasi_bk`;
SET FOREIGN_KEY_CHECKS = 0;

    DROP TABLE IF EXISTS `notifikasis`;
    DROP TABLE IF EXISTS `tindak_lanjut`;
    DROP TABLE IF EXISTS `konseling`;
    DROP TABLE IF EXISTS `penjadwalan`;
    DROP TABLE IF EXISTS `slot_konseling`;
    DROP TABLE IF EXISTS `jadwal_mengajar_bk`;
    DROP TABLE IF EXISTS `siswa`;
    DROP TABLE IF EXISTS `users`;
    DROP TABLE IF EXISTS `jenis_masalah`;
    DROP TABLE IF EXISTS `kelas`;
    DROP TABLE IF EXISTS `migrations`;
    DROP TABLE IF EXISTS `failed_jobs`;
    DROP TABLE IF EXISTS `password_resets`;
    DROP TABLE IF EXISTS `personal_access_tokens`;

    CREATE TABLE `kelas` (
      `id_kelas` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
      `nama_kelas` varchar(50) NOT NULL,
      `tingkat` int(11) NOT NULL,
      PRIMARY KEY (`id_kelas`)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

    CREATE TABLE `jenis_masalah` (
      `id_jenis` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
      `nama_jenis` varchar(100) NOT NULL,
      `keterangan` text DEFAULT NULL,
      PRIMARY KEY (`id_jenis`)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

    CREATE TABLE `users` (
      `id_user` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
      `username` varchar(255) NOT NULL,
      `email` varchar(255) NOT NULL,
      `password` varchar(255) NOT NULL,
      `nama` varchar(255) NOT NULL,
      `role` varchar(20) NOT NULL DEFAULT 'wali_kelas',
      `id_kelas` bigint(20) unsigned DEFAULT NULL,
      `foto_profil` varchar(255) DEFAULT NULL,
      PRIMARY KEY (`id_user`),
      UNIQUE KEY `users_email_unique` (`email`),
      KEY `users_id_kelas_foreign` (`id_kelas`),
      CONSTRAINT `users_id_kelas_foreign` FOREIGN KEY (`id_kelas`) REFERENCES `kelas` (`id_kelas`) ON DELETE SET NULL
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

    CREATE TABLE `siswa` (
      `id_siswa` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
      `nis` varchar(20) NOT NULL,
      `nama_siswa` varchar(100) NOT NULL,
      `jenis_kelamin` enum('Laki-laki','Perempuan') NOT NULL,
      `id_kelas` bigint(20) unsigned NOT NULL,
      `alamat` text DEFAULT NULL,
      `no_telp` varchar(15) DEFAULT NULL,
      `status` varchar(20) NOT NULL DEFAULT 'Aktif',
      PRIMARY KEY (`id_siswa`),
      KEY `fk_siswa_kelas` (`id_kelas`),
      CONSTRAINT `fk_siswa_kelas` FOREIGN KEY (`id_kelas`) REFERENCES `kelas` (`id_kelas`) ON DELETE CASCADE
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

    CREATE TABLE `konseling` (
      `id_konseling` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
      `id_siswa` bigint(20) unsigned NOT NULL,
      `id_jenis` bigint(20) unsigned NOT NULL,
      `tanggal` date NOT NULL,
      `masalah` text NOT NULL,
      `hasil_konseling` text DEFAULT NULL,
      `diagnosis` text DEFAULT NULL,
      `rencana_tindak_lanjut` text DEFAULT NULL,
      `catatan` text DEFAULT NULL,
      `status` varchar(20) NOT NULL DEFAULT 'Proses',
      PRIMARY KEY (`id_konseling`),
      KEY `fk_konseling_siswa` (`id_siswa`),
      KEY `fk_konseling_jenis` (`id_jenis`),
      CONSTRAINT `fk_konseling_jenis` FOREIGN KEY (`id_jenis`) REFERENCES `jenis_masalah` (`id_jenis`) ON DELETE CASCADE,
      CONSTRAINT `fk_konseling_siswa` FOREIGN KEY (`id_siswa`) REFERENCES `siswa` (`id_siswa`) ON DELETE CASCADE
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

    CREATE TABLE `tindak_lanjut` (
      `id_tindak_lanjut` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
      `id_konseling` bigint(20) unsigned NOT NULL,
      `tanggal` date NOT NULL,
      `tindakan` text NOT NULL,
      `keterangan` text DEFAULT NULL,
      `status` varchar(20) NOT NULL DEFAULT 'Belum Dilakukan',
      `tanggal_evaluasi` date DEFAULT NULL,
      `catatan_perkembangan` text DEFAULT NULL,
      `hasil_evaluasi` text DEFAULT NULL,
      PRIMARY KEY (`id_tindak_lanjut`),
      KEY `fk_tindak_lanjut_konseling` (`id_konseling`),
      CONSTRAINT `fk_tindak_lanjut_konseling` FOREIGN KEY (`id_konseling`) REFERENCES `konseling` (`id_konseling`) ON DELETE CASCADE
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

    CREATE TABLE `slot_konseling` (
      `id_slot` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
      `id_guru_bk` bigint(20) unsigned NOT NULL,
      `tanggal` date NOT NULL,
      `waktu_mulai` time NOT NULL,
      `waktu_selesai` time NOT NULL,
      `durasi_menit` int(11) NOT NULL DEFAULT 45,
      `status_slot` enum('Tersedia','Menunggu_Diproses','Dipesan','Tidak_Tersedia') NOT NULL DEFAULT 'Tersedia',
      `catatan` text DEFAULT NULL,
      `created_at` timestamp NULL DEFAULT NULL,
      `updated_at` timestamp NULL DEFAULT NULL,
      PRIMARY KEY (`id_slot`),
      KEY `slot_konseling_id_guru_bk_foreign` (`id_guru_bk`),
      CONSTRAINT `slot_konseling_id_guru_bk_foreign` FOREIGN KEY (`id_guru_bk`) REFERENCES `users` (`id_user`) ON DELETE CASCADE
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

    CREATE TABLE `penjadwalan` (
      `id_penjadwalan` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
      `kode_pengajuan` varchar(20) NOT NULL,
      `id_siswa` bigint(20) unsigned NOT NULL,
      `id_slot` bigint(20) unsigned DEFAULT NULL,
      `tanggal` date NOT NULL,
      `waktu_mulai` time NOT NULL,
      `waktu_selesai` time NOT NULL,
      `jenis_bimbingan` varchar(50) NOT NULL,
      `catatan` text DEFAULT NULL,
      `status` enum('Diajukan','Disetujui_Wali','Ditolak_Wali','Terjadwal','Selesai','Dibatalkan') NOT NULL DEFAULT 'Diajukan',
      `id_wali` bigint(20) unsigned DEFAULT NULL,
      `waktu_persetujuan_wali` timestamp NULL DEFAULT NULL,
      `catatan_wali` text DEFAULT NULL,
      `created_at` timestamp NULL DEFAULT NULL,
      `updated_at` timestamp NULL DEFAULT NULL,
      PRIMARY KEY (`id_penjadwalan`),
      UNIQUE KEY `penjadwalan_kode_pengajuan_unique` (`kode_pengajuan`),
      KEY `penjadwalan_id_siswa_foreign` (`id_siswa`),
      KEY `penjadwalan_id_wali_foreign` (`id_wali`),
      KEY `penjadwalan_id_slot_foreign` (`id_slot`),
      CONSTRAINT `penjadwalan_id_siswa_foreign` FOREIGN KEY (`id_siswa`) REFERENCES `siswa` (`id_siswa`) ON DELETE CASCADE,
      CONSTRAINT `penjadwalan_id_slot_foreign` FOREIGN KEY (`id_slot`) REFERENCES `slot_konseling` (`id_slot`) ON DELETE SET NULL,
      CONSTRAINT `penjadwalan_id_wali_foreign` FOREIGN KEY (`id_wali`) REFERENCES `users` (`id_user`) ON DELETE SET NULL
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

    CREATE TABLE `jadwal_mengajar_bk` (
      `id_jadwal_mengajar` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
      `id_guru_bk` bigint(20) unsigned NOT NULL,
      `hari` varchar(10) NOT NULL,
      `tanggal` date DEFAULT NULL,
      `waktu_mulai` time NOT NULL,
      `waktu_selesai` time NOT NULL,
      `id_kelas` bigint(20) unsigned DEFAULT NULL,
      `mata_pelajaran` varchar(100) DEFAULT NULL,
      `catatan` text DEFAULT NULL,
      `is_active` tinyint(1) NOT NULL DEFAULT 1,
      `created_at` timestamp NULL DEFAULT NULL,
      `updated_at` timestamp NULL DEFAULT NULL,
      PRIMARY KEY (`id_jadwal_mengajar`),
      KEY `jadwal_mengajar_bk_id_guru_bk_foreign` (`id_guru_bk`),
      KEY `jadwal_mengajar_bk_id_kelas_foreign` (`id_kelas`),
      CONSTRAINT `jadwal_mengajar_bk_id_guru_bk_foreign` FOREIGN KEY (`id_guru_bk`) REFERENCES `users` (`id_user`) ON DELETE CASCADE,
      CONSTRAINT `jadwal_mengajar_bk_id_kelas_foreign` FOREIGN KEY (`id_kelas`) REFERENCES `kelas` (`id_kelas`) ON DELETE SET NULL
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

    CREATE TABLE `notifikasis` (
      `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
      `judul` varchar(255) NOT NULL,
      `pesan` text NOT NULL,
      `tipe` varchar(50) NOT NULL,
      `dibaca` tinyint(1) NOT NULL DEFAULT 0,
      `id_konseling` bigint(20) unsigned DEFAULT NULL,
      `id_kelas` bigint(20) unsigned DEFAULT NULL,
      `id_user` bigint(20) unsigned NOT NULL,
      `created_at` timestamp NULL DEFAULT NULL,
      `updated_at` timestamp NULL DEFAULT NULL,
      PRIMARY KEY (`id`)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

    CREATE TABLE `migrations` (
      `id` int(10) unsigned NOT NULL AUTO_INCREMENT,
      `migration` varchar(255) NOT NULL,
      `batch` int(11) NOT NULL,
      PRIMARY KEY (`id`)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
    
